-- Run once in the Supabase SQL Editor before deploying the reminder function.

create table if not exists public.membership_expiry_reminders (
  id bigint generated by default as identity primary key,
  member_id uuid not null references public.members(id) on delete cascade,
  expiry date not null,
  days_remaining integer not null check (days_remaining >= 0),
  recipient_email text not null,
  sent_at timestamptz not null default now(),
  unique (member_id, expiry, days_remaining)
);

alter table public.membership_expiry_reminders enable row level security;
revoke all on public.membership_expiry_reminders from anon, authenticated;
